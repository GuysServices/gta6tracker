// Fallback: derive approximate position from area string keywords
function inferPos(area: string): { x: number; y: number } {
  const a = area.toLowerCase()
  if (a.includes('vice beach') || a.includes('ocean beach') || a.includes('washington beach')) return { x: 75, y: 74 }
  if (a.includes('vice city') || a.includes('vice-dale')) return { x: 70, y: 65 }
  if (a.includes('port gellhorn')) return { x: 22, y: 55 }
  if (a.includes('key lento') || a.includes('keys')) return { x: 54, y: 90 }
  if (a.includes('mariana')) return { x: 32, y: 78 }
  if (a.includes('kelly')) return { x: 28, y: 42 }
  if (a.includes('lummox')) return { x: 44, y: 25 }
  if (a.includes('leonard')) return { x: 60, y: 32 }
  if (a.includes('belville')) return { x: 62, y: 36 }
  if (a.includes('waning sands')) return { x: 60, y: 48 }
  if (a.includes('capri')) return { x: 30, y: 52 }
  if (a.includes('ambrosia')) return { x: 54, y: 46 }
  if (a.includes('hamlet')) return { x: 48, y: 60 }
  if (a.includes('watson')) return { x: 24, y: 36 }
  if (a.includes('millport')) return { x: 48, y: 18 }
  if (a.includes('redhill')) return { x: 56, y: 18 }
  if (a.includes('goose key')) return { x: 22, y: 88 }
  if (a.includes('maroon key')) return { x: 18, y: 86 }
  return { x: 50, y: 50 }
}

// Add slight deterministic jitter so multiple pins in one area don't stack
function jitter(base: { x: number; y: number }, id: number): { x: number; y: number } {
  const angle = (id * 137.508) % 360  // golden angle spread
  const r = 1.2 + (id % 5) * 0.6
  return {
    x: +(base.x + r * Math.cos(angle * Math.PI / 180)).toFixed(2),
    y: +(base.y + r * Math.sin(angle * Math.PI / 180)).toFixed(2),
  }
}

function getPos(area: string, id: number): { x: number; y: number } {
  const base = AREA_POS[area] ?? inferPos(area)
  return jitter(base, id)
}

